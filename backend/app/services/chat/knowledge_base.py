def get_localized_response(intent: str, language_code: str, subkey: Optional[str] = None) -> str:
    """
    Retrieves localized high-precision response for a specific intent and language code.
    Falls back to English if the specific language translation is not present.
    """
    lang_dict = LOCALIZED_RESPONSES.get(language_code.lower()) or LOCALIZED_RESPONSES["en"]
    
    key = subkey or INTENT_KEY_ALIASES.get(intent, intent)
    if key in lang_dict:
        return lang_dict[key]
    
    # Fallback to English
    fallback_dict = LOCALIZED_RESPONSES["en"]
    return fallback_dict.get(key, fallback_dict.get("unknown", "Please clarify your dairy question."))

